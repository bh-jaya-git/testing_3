CREATE OR REPLACE PROCEDURE zenith_expense_types_incremental_merge_261105_7d9c()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
BEGIN
BEGIN TRANSACTION;

MERGE INTO SF_BIGHAMMER.RAW.RAW_ZENITH_CRM_PORTALCLIENTLOG AS target
USING (
WITH RAW_ZENITH_CRM_FINANCIALEXPENSETYPE AS (
    SELECT ID AS ID_src_1, NAME AS NAME_src_1, LOAD_TIMESTAMP AS LOAD_TIMESTAMP_src_1, SOURCE_BLOB_FILE_NAME AS SOURCE_BLOB_FILE_NAME_src_1, CDC_OPERATION AS CDC_OPERATION_src_1 FROM SF_BIGHAMMER.RAW.RAW_ZENITH_CRM_FINANCIALEXPENSETYPE
),
DIM_CRM_EXPENSE_TYPES_rename AS (
    SELECT EXPENSE_TYPE_ID, EXPENSE_TYPE_DESCRIPTION, SRC_CREATED_AT, LOAD_TIMESTAMP_src_1 AS SRC_MODIFIED_AT, SRC_CREATED_BY, SOURCE_BLOB_FILE_NAME_src_1 AS SRC_MODIFIED_BY, CAST(ID_src_1 AS BIGINT) AS SOURCE_SYSTEM_ID FROM RAW_ZENITH_CRM_FINANCIALEXPENSETYPE
),
RAW_ZENITH_CRM_PORTALCLIENTLOG_expression AS (
    SELECT ID_src_1 AS ID, LOAD_TIMESTAMP_src_1 AS LOAD_TIMESTAMP, SOURCE_BLOB_FILE_NAME_src_1 AS SOURCE_BLOB_FILE_NAME, CDC_OPERATION_src_1 AS CDC_OPERATION FROM RAW_ZENITH_CRM_FINANCIALEXPENSETYPE
),
DIM_CRM_EXPENSE_TYPES_final AS (
    SELECT EXPENSE_TYPE_ID, EXPENSE_TYPE_DESCRIPTION, SRC_CREATED_AT, SRC_MODIFIED_AT, SRC_CREATED_BY, SRC_MODIFIED_BY, SOURCE_SYSTEM_ID, CAST(NULL AS TIMESTAMPTZ) AS CREATED_AT, CAST(NULL AS TIMESTAMPTZ) AS MODIFIED_AT FROM DIM_CRM_EXPENSE_TYPES_rename
)
SELECT ID, CLIENTID, LOGTYPEID, IPADDRESS, USERAGENT, EXTRA, LOGDATE, TOKEN, ENCRYPTAUTOLOGINMESSAGE, AESKEY, AESIV, LOAD_TIMESTAMP, SOURCE_BLOB_FILE_NAME, CDC_OPERATION FROM RAW_ZENITH_CRM_PORTALCLIENTLOG_expression
) AS source
ON target.ID = source.ID
WHEN MATCHED THEN UPDATE SET target.CLIENTID = source.CLIENTID, target.LOGTYPEID = source.LOGTYPEID, target.IPADDRESS = source.IPADDRESS, target.USERAGENT = source.USERAGENT, target.EXTRA = source.EXTRA, target.LOGDATE = source.LOGDATE, target.TOKEN = source.TOKEN, target.ENCRYPTAUTOLOGINMESSAGE = source.ENCRYPTAUTOLOGINMESSAGE, target.AESKEY = source.AESKEY, target.AESIV = source.AESIV, target.LOAD_TIMESTAMP = source.LOAD_TIMESTAMP, target.SOURCE_BLOB_FILE_NAME = source.SOURCE_BLOB_FILE_NAME, target.CDC_OPERATION = source.CDC_OPERATION
WHEN NOT MATCHED THEN INSERT (ID, CLIENTID, LOGTYPEID, IPADDRESS, USERAGENT, EXTRA, LOGDATE, TOKEN, ENCRYPTAUTOLOGINMESSAGE, AESKEY, AESIV, LOAD_TIMESTAMP, SOURCE_BLOB_FILE_NAME, CDC_OPERATION) VALUES (source.ID, source.CLIENTID, source.LOGTYPEID, source.IPADDRESS, source.USERAGENT, source.EXTRA, source.LOGDATE, source.TOKEN, source.ENCRYPTAUTOLOGINMESSAGE, source.AESKEY, source.AESIV, source.LOAD_TIMESTAMP, source.SOURCE_BLOB_FILE_NAME, source.CDC_OPERATION);

MERGE INTO SF_BIGHAMMER.SILVER.DIM_CRM_EXPENSE_TYPES AS target
USING (
WITH RAW_ZENITH_CRM_FINANCIALEXPENSETYPE AS (
    SELECT ID AS ID_src_1, NAME AS NAME_src_1, LOAD_TIMESTAMP AS LOAD_TIMESTAMP_src_1, SOURCE_BLOB_FILE_NAME AS SOURCE_BLOB_FILE_NAME_src_1, CDC_OPERATION AS CDC_OPERATION_src_1 FROM SF_BIGHAMMER.RAW.RAW_ZENITH_CRM_FINANCIALEXPENSETYPE
),
DIM_CRM_EXPENSE_TYPES_rename AS (
    SELECT EXPENSE_TYPE_ID, EXPENSE_TYPE_DESCRIPTION, SRC_CREATED_AT, LOAD_TIMESTAMP_src_1 AS SRC_MODIFIED_AT, SRC_CREATED_BY, SOURCE_BLOB_FILE_NAME_src_1 AS SRC_MODIFIED_BY, CAST(ID_src_1 AS BIGINT) AS SOURCE_SYSTEM_ID FROM RAW_ZENITH_CRM_FINANCIALEXPENSETYPE
),
RAW_ZENITH_CRM_PORTALCLIENTLOG_expression AS (
    SELECT ID_src_1 AS ID, LOAD_TIMESTAMP_src_1 AS LOAD_TIMESTAMP, SOURCE_BLOB_FILE_NAME_src_1 AS SOURCE_BLOB_FILE_NAME, CDC_OPERATION_src_1 AS CDC_OPERATION FROM RAW_ZENITH_CRM_FINANCIALEXPENSETYPE
),
DIM_CRM_EXPENSE_TYPES_final AS (
    SELECT EXPENSE_TYPE_ID, EXPENSE_TYPE_DESCRIPTION, SRC_CREATED_AT, SRC_MODIFIED_AT, SRC_CREATED_BY, SRC_MODIFIED_BY, SOURCE_SYSTEM_ID, CAST(NULL AS TIMESTAMPTZ) AS CREATED_AT, CAST(NULL AS TIMESTAMPTZ) AS MODIFIED_AT FROM DIM_CRM_EXPENSE_TYPES_rename
)
SELECT EXPENSE_TYPE_ID, EXPENSE_TYPE_DESCRIPTION, SRC_CREATED_AT, SRC_MODIFIED_AT, SRC_CREATED_BY, SRC_MODIFIED_BY, CREATED_AT, MODIFIED_AT, SOURCE_SYSTEM_ID FROM DIM_CRM_EXPENSE_TYPES_final
) AS source
ON target.EXPENSE_TYPE_ID = source.EXPENSE_TYPE_ID
WHEN MATCHED THEN UPDATE SET target.EXPENSE_TYPE_DESCRIPTION = source.EXPENSE_TYPE_DESCRIPTION, target.SRC_CREATED_AT = source.SRC_CREATED_AT, target.SRC_MODIFIED_AT = source.SRC_MODIFIED_AT, target.SRC_CREATED_BY = source.SRC_CREATED_BY, target.SRC_MODIFIED_BY = source.SRC_MODIFIED_BY, target.MODIFIED_AT = source.MODIFIED_AT, target.SOURCE_SYSTEM_ID = source.SOURCE_SYSTEM_ID
WHEN NOT MATCHED THEN INSERT (EXPENSE_TYPE_ID, EXPENSE_TYPE_DESCRIPTION, SRC_CREATED_AT, SRC_MODIFIED_AT, SRC_CREATED_BY, SRC_MODIFIED_BY, CREATED_AT, MODIFIED_AT, SOURCE_SYSTEM_ID) VALUES (source.EXPENSE_TYPE_ID, source.EXPENSE_TYPE_DESCRIPTION, source.SRC_CREATED_AT, source.SRC_MODIFIED_AT, source.SRC_CREATED_BY, source.SRC_MODIFIED_BY, source.CREATED_AT, source.MODIFIED_AT, source.SOURCE_SYSTEM_ID);

COMMIT;

    RETURN 'Success';
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END
$$;